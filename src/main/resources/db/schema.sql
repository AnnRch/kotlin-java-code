CREATE MATERIALIZED VIEW IF NOT EXISTS public.mv_search_analytics_summary_30_days AS
WITH summary_metrics AS (
    SELECT
        'endpoint' AS metric_type,
        endpoint AS metric_key,
        COUNT(*) AS metric_count,
        ROUND(AVG(results_count)) AS avg_results,
        0::BIGINT AS zero_result_searches
    FROM public.search_analytics_events
    WHERE created_at >= NOW() - INTERVAL '30 days' AND endpoint IS NOT NULL
    GROUP BY endpoint

    UNION ALL

    SELECT
        'query' AS metric_type,
        search_query AS metric_key,
        COUNT(*) AS metric_count,
        ROUND(AVG(results_count)) AS avg_results,
        0::BIGINT AS zero_result_searches
    FROM public.search_analytics_events
    WHERE created_at >= NOW() - INTERVAL '30 days' AND search_query IS NOT NULL
    GROUP BY search_query

    UNION ALL

    SELECT
        'tag' AS metric_type,
        UNNEST(tags) AS metric_key,
        COUNT(*) AS metric_count,
        0::BIGINT AS avg_results,
        0::BIGINT AS zero_result_searches
    FROM public.search_analytics_events
    WHERE created_at >= NOW() - INTERVAL '30 days' AND tags IS NOT NULL
    GROUP BY metric_key

    UNION ALL

    SELECT
        'counter' AS metric_type,
        'global' AS metric_key,
        COUNT(*) AS metric_count,
        0::BIGINT AS avg_results,
        COUNT(*) FILTER (WHERE results_count = 0) AS zero_result_searches
    FROM public.search_analytics_events
    WHERE created_at >= NOW() - INTERVAL '30 days'
)
SELECT * FROM summary_metrics;

CREATE UNIQUE INDEX IF NOT EXISTS idx_mv_search_summary_unique
    ON public.mv_search_analytics_summary_30_days (metric_type, metric_key);

