CREATE OR REPLACE FUNCTION public.update_company_stats_incremental()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
DECLARE
old_slug VARCHAR(100);
    new_slug VARCHAR(100);
BEGIN
    IF (TG_OP = 'INSERT' OR TG_OP = 'UPDATE') THEN
SELECT slug INTO new_slug FROM public.companies WHERE id = NEW.company_id;
END IF;

    IF (TG_OP = 'DELETE' OR TG_OP = 'UPDATE') THEN
SELECT slug INTO old_slug FROM public.companies WHERE id = OLD.company_id;
END IF;

--     INSERT
    IF (TG_OP = 'INSERT') THEN
        IF new_slug IS NOT NULL THEN
UPDATE public.companies SET
        total_jobs = total_jobs + 1,
        avg_salary_all = CASE
            WHEN salary_count_all = 0 THEN ((COALESCE(NEW.salary_min, 0) + COALESCE(NEW.salary_max, 0)) / 2)
             ELSE ((avg_salary_all * salary_count_all) + ((COALESCE(NEW.salary_min, 0) + COALESCE(NEW.salary_max, 0)) / 2)) / (salary_count_all + 1)
                END,
        salary_count_all = salary_count_all + 1
WHERE slug = new_slug;
END IF;

    -- DELETE
    ELSIF (TG_OP = 'DELETE') THEN
        IF old_slug IS NOT NULL THEN
UPDATE public.companies SET
        total_jobs = CASE WHEN total_jobs > 0 THEN total_jobs - 1 ELSE 0 END,
        avg_salary_all = CASE
        WHEN salary_count_all > 1 THEN
        COALESCE(((avg_salary_all * salary_count_all) - ((COALESCE(OLD.salary_min, 0) + COALESCE(OLD.salary_max, 0)) / 2)) / (salary_count_all - 1), 0)
        ELSE 0
        END,
    salary_count_all = CASE WHEN salary_count_all > 0 THEN salary_count_all - 1 ELSE 0 END
WHERE slug = old_slug;
END IF;

    -- UPDATE
    ELSIF (TG_OP = 'UPDATE') THEN
        -- The job moved to a completely different company
        IF (COALESCE(NEW.company_id, 0) != COALESCE(OLD.company_id, 0)) THEN
            -- Remove from old company
            IF old_slug IS NOT NULL THEN
            UPDATE public.companies SET
                        total_jobs = CASE WHEN total_jobs > 0 THEN total_jobs - 1 ELSE 0 END,
                         avg_salary_all = CASE
                             WHEN salary_count_all > 1 THEN
                            COALESCE(((avg_salary_all * salary_count_all) - ((COALESCE(OLD.salary_min, 0) + COALESCE(OLD.salary_max, 0)) / 2)) / (salary_count_all - 1), 0)
                                ELSE 0
                                END,
                        salary_count_all = CASE WHEN salary_count_all > 0 THEN salary_count_all - 1 ELSE 0 END
WHERE slug = old_slug;
END IF;

            -- Add to new company
            IF new_slug IS NOT NULL THEN
            UPDATE public.companies SET
                    total_jobs = total_jobs + 1,
                    avg_salary_all = CASE
                        WHEN salary_count_all = 0 THEN ((COALESCE(NEW.salary_min, 0) + COALESCE(NEW.salary_max, 0)) / 2)
                        ELSE ((avg_salary_all * salary_count_all) + ((COALESCE(NEW.salary_min, 0) + COALESCE(NEW.salary_max, 0)) / 2)) / (salary_count_all + 1)
                            END,
                    salary_count_all = salary_count_all + 1
WHERE slug = new_slug;
END IF;
        -- Same company, but the salary numbers changed
        ELSIF (COALESCE(NEW.salary_min, 0) != COALESCE(OLD.salary_min, 0) OR COALESCE(NEW.salary_max, 0) != COALESCE(OLD.salary_max, 0)) THEN
            IF new_slug IS NOT NULL THEN
UPDATE public.companies SET
    avg_salary_all = CASE
             WHEN public.companies.salary_count_all <= 1 THEN
                ((COALESCE(NEW.salary_min, 0) + COALESCE(NEW.salary_max, 0)) / 2)
                ELSE
                    ((public.companies.avg_salary_all * public.companies.salary_count_all)
                            - ((COALESCE(OLD.salary_min, 0) + COALESCE(OLD.salary_max, 0)) / 2)
                            + ((COALESCE(NEW.salary_min, 0) + COALESCE(NEW.salary_max, 0)) / 2))
                             / public.companies.salary_count_all
        END
WHERE slug = new_slug;
END IF;
END IF;
END IF;

RETURN NEW;
END;
$function$;

CREATE TRIGGER trigger_update_company_stats_incremental
    AFTER INSERT OR
UPDATE OR
DELETE
ON public.jobs
    FOR EACH ROW
    EXECUTE FUNCTION public.update_company_stats_incremental();

